"""Exporters: datasets, a reproducibility report, and runnable scripts.

Beyond the simulated data itself, a researcher needs to be able to *justify* and
*reproduce* it. So alongside the trial-level and cell-mean CSVs we emit:

* a human-readable reproducibility report (design, formula, priors, seed,
  convergence diagnostics, package versions), and
* the equivalent **Bambi (Python)** and **brms (R)** scripts, so the exact
  modeling pipeline is transparent and re-runnable in either ecosystem.
"""

from __future__ import annotations

import json
from textwrap import indent
from typing import Any

from .formula import build_formula, brms_formula, brms_family
from .spec import FAMILY_INFO, OutcomeFamily, StudyDesign


# --------------------------------------------------------------------------- #
# Reproducibility report
# --------------------------------------------------------------------------- #
def reproducibility_report(design: StudyDesign, *, source: str,
                           n_participants: int, seed: int,
                           diagnostics: dict[str, Any] | None = None,
                           sample_kwargs: dict[str, Any] | None = None) -> str:
    lines: list[str] = []
    a = lines.append
    a(f"# Reproducibility report: {design.name}\n")
    a("_Generated by Counterfactual Participant Studio "
      "(method after While & Sarvghad, CHI '25)._\n")

    a("## Generation summary\n")
    a(f"- Source of cell parameters: **{source}** "
      f"({'fit to your data' if source == 'posterior' else 'your stated assumptions'})")
    a(f"- Counterfactual participants generated: **{n_participants:,}**")
    a(f"- Random seed: `{seed}`")
    if sample_kwargs:
        a(f"- Sampler settings: `{json.dumps(sample_kwargs)}`")
    a("")

    a("## Study design\n")
    a(f"- Grouping unit: `{design.grouping}`")
    a(f"- Drop global intercept (cell-means coding): `{design.drop_intercept}`")
    io = design.interaction_order
    a(f"- Interaction order: `{'full' if io is None else io}`\n")
    a("### Factors\n")
    a("| Factor | Kind | Role | Levels |")
    a("| --- | --- | --- | --- |")
    for f in design.factors:
        lv = ", ".join(map(str, f.levels)) if f.levels else "(continuous)"
        a(f"| `{f.name}` | {f.kind.value} | {f.role.value} | {lv} |")
    a("")
    a("### Outcomes\n")
    a("| Outcome | Family | Notes | Trials/cell |")
    a("| --- | --- | --- | --- |")
    for o in design.outcomes:
        note = FAMILY_INFO[o.family]["label"]
        if o.family == OutcomeFamily.BERNOULLI and o.guess_rate:
            note += f", chance floor = {o.guess_rate:.0%}"
        a(f"| `{o.name}` | {o.family.value} | {note} | {o.trials_per_cell} |")
    a("")

    a("## Models\n")
    for o in design.outcomes:
        parts = build_formula(design, o)
        a(f"### `{o.name}`\n")
        a(f"- Bambi family: `{parts.bambi_family}`"
          + ("  (gaussian on `log` of the response)" if parts.needs_log_transform else ""))
        a(f"- Bambi formula: `{parts.bambi_formula}`")
        a(f"- brms formula: `{brms_formula(design, o)}`, family `{brms_family(o)}`")
        if diagnostics and o.name in diagnostics:
            d = diagnostics[o.name]
            a(f"- Convergence: **{d['status']}** "
              f"(max R-hat = {d['max_rhat']:.3f}, min bulk ESS = {d['min_ess_bulk']:.0f}, "
              f"divergences = {d['n_divergences']})")
            a(f"  - {d['interpretation']}")
        a("")

    a("## Software\n")
    a(_versions_block())
    return "\n".join(lines)


def _versions_block() -> str:
    pkgs = ["bambi", "pymc", "arviz", "pytensor", "numpy", "pandas", "scipy"]
    out = []
    for p in pkgs:
        try:
            mod = __import__(p)
            out.append(f"- {p}=={getattr(mod, '__version__', '?')}")
        except Exception:
            out.append(f"- {p}==(not installed)")
    return "\n".join(out)


